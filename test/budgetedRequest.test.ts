import { describe, expect, it, vi } from "vitest";
import { RequestTooLargeError } from "../src/electron/main/providers/errors";
import { OMITTED_SCREENSHOT_NOTE } from "../src/electron/main/providers/messageBuilder";
import { createBudgetTrace, runBudgetedRequest } from "../src/electron/main/runtime/budgetedRequest";
import { HistoryWindow } from "../src/electron/main/runtime/historyWindow";
import type { DanmakuGenerationResult, DanmakuInput } from "../src/shared/types";
import { makeConfig, makeSnapshot } from "./helpers";

const MIB = 1024 * 1024;
const LLM_API_413 = "Request Entity Too Large\n\nexceeds max_body of 67108864\n\n(generated by llm_api)";

function okResult(): DanmakuGenerationResult {
  return { items: [{ id: "1", text: "ok", createdAt: "" }], userText: "", assistantText: '{"comments":["ok"]}' };
}

function filledHistory(rounds: number, imageBytes: number): HistoryWindow {
  const history = new HistoryWindow();
  for (let index = 0; index < rounds; index += 1) {
    history.remember(
      { items: [{ id: `${index}`, text: `c${index}`, createdAt: "" }], userText: "", assistantText: `{"comments":["c${index}"]}` },
      makeSnapshot(imageBytes),
      { historyRounds: 50, historyMode: "reset-on-limit", historyIncludeImages: true },
      index,
    );
  }
  return history;
}

const config = makeConfig({ model: { visionEnabled: true } });
const input = { character: config.character, maxItems: 3 };

describe("runBudgetedRequest", () => {
  it("sends history untouched while under budget", async () => {
    const history = filledHistory(5, 100_000);
    const generate = vi.fn(async (_input: DanmakuInput) => okResult());
    const trace = createBudgetTrace();
    await runBudgetedRequest(
      { config, history, input, snapshot: makeSnapshot(100_000), trace, settings: { historyRounds: 50, historyMaxImages: 12, requestBodyLimitBytes: 48 * MIB } },
      { generate },
    );
    expect(generate).toHaveBeenCalledTimes(1);
    expect(generate.mock.calls[0][0].history).toHaveLength(5);
    expect(trace.historyImagesSent).toBe(5);
    expect(trace.compaction).toEqual([]);
    expect(generate.mock.calls[0][0].maxBodyBytes).toBe(48 * MIB);
  });

  it("compacts in a batch and keeps the compacted history for the next request", async () => {
    const history = filledHistory(13, 100_000);
    const generate = vi.fn(async (_input: DanmakuInput) => okResult());
    const trace = createBudgetTrace();
    await runBudgetedRequest(
      { config, history, input, snapshot: makeSnapshot(100_000), trace, settings: { historyRounds: 50, historyMaxImages: 12, requestBodyLimitBytes: 48 * MIB } },
      { generate },
    );
    const sent = generate.mock.calls[0][0].history ?? [];
    expect(trace.compaction).toEqual([{ trigger: "budget", reason: "images", droppedImages: 7 }]);
    expect(sent.filter((round) => round.snapshot)).toHaveLength(6);
    expect(sent.slice(0, 7).every((round) => round.imageOmitted)).toBe(true);
    expect(history.imageCount).toBe(6);
  });

  it("learns the server limit from a 413, compacts and retries once", async () => {
    const history = filledHistory(10, 7 * MIB);
    const generate = vi
      .fn(async (_input: DanmakuInput) => okResult())
      .mockRejectedValueOnce(
        new RequestTooLargeError({ message: "413", requestBytes: 73 * MIB, serverBody: LLM_API_413, fromServer: true }),
      );
    const trace = createBudgetTrace();
    await runBudgetedRequest(
      // A user-configured limit above the server's real one.
      { config, history, input, snapshot: makeSnapshot(7 * MIB), trace, settings: { historyRounds: 50, historyMaxImages: 50, requestBodyLimitBytes: 128 * MIB } },
      { generate },
    );
    expect(generate).toHaveBeenCalledTimes(2);
    expect(trace.learnedLimitBytes).toBe(Math.floor(67108864 * 0.95));
    expect(trace.compaction.map((entry) => entry.trigger)).toEqual(["413"]);
    expect(generate.mock.calls[1][0].maxBodyBytes).toBe(Math.floor(67108864 * 0.95));
  });

  it("does not retry twice", async () => {
    const history = filledHistory(2, 1000);
    const error = new RequestTooLargeError({ message: "413", requestBytes: 2000, serverBody: "", fromServer: true });
    const generate = vi.fn(async (_input: DanmakuInput): Promise<DanmakuGenerationResult> => {
      throw error;
    });
    await expect(
      runBudgetedRequest(
        { config, history, input, trace: createBudgetTrace(), settings: { historyRounds: 50, historyMaxImages: 12, requestBodyLimitBytes: 48 * MIB } },
        { generate },
      ),
    ).rejects.toBe(error);
    expect(generate).toHaveBeenCalledTimes(2);
  });

  it("does not retry other errors", async () => {
    const generate = vi.fn(async (_input: DanmakuInput): Promise<DanmakuGenerationResult> => {
      throw new Error("HTTP 500");
    });
    await expect(
      runBudgetedRequest(
        { config, history: new HistoryWindow(), input, trace: createBudgetTrace(), settings: { historyRounds: 4, historyMaxImages: 12, requestBodyLimitBytes: MIB } },
        { generate },
      ),
    ).rejects.toThrow("HTTP 500");
    expect(generate).toHaveBeenCalledTimes(1);
  });

  it("shrinks a current screenshot that alone exceeds the budget", async () => {
    const generate = vi.fn(async (_input: DanmakuInput) => okResult());
    const shrinkSnapshot = vi.fn((_snapshot, maxBytes: number) => makeSnapshot(Math.min(200_000, maxBytes - 10)));
    const trace = createBudgetTrace();
    await runBudgetedRequest(
      { config, history: new HistoryWindow(), input, snapshot: makeSnapshot(3 * MIB), trace, settings: { historyRounds: 4, historyMaxImages: 12, requestBodyLimitBytes: MIB } },
      { generate, shrinkSnapshot },
    );
    expect(shrinkSnapshot).toHaveBeenCalledTimes(1);
    expect(shrinkSnapshot.mock.calls[0][1]).toBeLessThan(MIB);
    expect(trace.resizedToFit).toBe(true);
    expect(generate.mock.calls[0][0].snapshot?.dataUrl.length).toBeLessThanOrEqual(200_000);
  });
});

describe("history messages after compaction", () => {
  it("marks dropped screenshots in the user turn", async () => {
    const { buildMessages } = await import("../src/electron/main/providers/messageBuilder");
    const { messages } = buildMessages(
      { ...input, history: [{ userText: "", assistantText: "{}", imageOmitted: true }] },
      config,
    );
    expect(messages[1].content).toEqual([{ type: "text", text: OMITTED_SCREENSHOT_NOTE }]);
  });
});
